#!/usr/bin/env python
"""Generate the report's LaTeX tables directly from the score tables.

WHY THIS IS A TOOL AND NOT TYPING
---------------------------------
`Guideline_for__Thesis__Writing.pdf` requires standard deviations with every
measurement. That is a constraint on the ANALYSIS, not the prose: a mean typed
into a .tex file by hand has no dispersion attached and no way to acquire one,
and it silently goes stale the moment a run is rescored. Every number the report
quotes is therefore emitted from the parquet that produced it, with its sd, and
regenerated by rerunning this script.

It also enforces the guideline's table rules, which are easy to breach by hand:
`booktabs` rules only, no vertical lines, every abbreviation expanded in the
caption, and a label so the text can reference the table (the guideline requires
that every table IS referenced).

Usage:
  python tools/make_report_tables.py --scores $WORK/prl26/results/scores \\
      --out report/tables
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
