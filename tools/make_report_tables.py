def t_judges(S):
    """Eight identity judges: how far each leans towards one method's encoder, and its verdict.

    Numbers come from tools/analyse_panel.py (panel.json), which needs the saved
    embeddings; see that script for the lean.
    """
    f = S / "panel.json"
    if not f.exists():
        return None
    P = json.loads(f.read_text())
    J, rows = P["judges"], []

    def lean(r):
        lo, hi = r["lean_ci"]
        return f"${r['lean']:+.2f}${'$^{*}$' if lo > 0 or hi < 0 else ''}"

    def dz(r):
        return f"${r['dz']:+.2f}${'$^{*}$' if r['p'] < 0.05 else ''}"
    for key, name in JUDGES:
        r4, r0 = J[key]["PuLID 4"], J[key]["PuLID 0"]
        rows.append([name, lean(r4), dz(r4), f"{r4['pulid_lower']:.0%}".replace("%", "\\%"),
                     lean(r0), dz(r0), f"{r0['pulid_lower']:.0%}".replace("%", "\\%")])
        if key == "w600k":
            rows.append(None)
    rows.append(None)
    p4, p0 = P["panel_PuLID 4"], P["panel_PuLID 0"]
    rows.append(["Neutral panel", "--", f"${p4['mean_sd_units']:+.2f}$$^{{*}}$",
                 f"{p4['pulid_lower']:.0%}".replace("%", "\\%"), "--",
                 f"${p0['mean_sd_units']:+.2f}$$^{{*}}$", f"{p0['pulid_lower']:.0%}".replace("%", "\\%")])
    return tex_table(
        "Eight identity judges",
        r"Each judge's lean (Equation~\ref{eq:lean}; negative towards PuLID's encoder) "
        r"and verdict: $d_z$, the mean per-cell ID Loss "
        r"difference (PuLID minus InfU) over its standard deviation, and the share of "
        r"cells where PuLID's loss is lower, on cells where both faces were found. "
        r"Below the first rule, judges outside the ArcFace family; the neutral panel "
        r"pools the four with no lean at either setting. $^{*}$: 95\% interval "
        r"excludes zero.",
        "tab:judges",
        ["Judge", "Lean", "$d_z$", "PuLID better", "Lean", "$d_z$", "PuLID better"],
        rows, align="lrrrrrr", size="footnotesize",
        pre_header=r"& \multicolumn{3}{c}{PuLID 4 against InfU} & \multicolumn{3}{c}{PuLID 0 against InfU} \\"
                   "\n    \\cmidrule(lr){2-4}\\cmidrule(lr){5-7}")


def t_part1_strata(S):
    """ID Loss by face size, under both methods' encoders.

    Under PuLID's encoder even close-ups sat far above the published level, which
    made composition look insufficient. Under InfU's encoder the close-up stratum
    is at or below it, so the table has to show both to show why.
    """
    d = load_part1(S)
    rows = []
    for stratum, label in [("closeup", "close-up"), ("waist", "waist"), ("full", "full body")]:
        g = {k: v[v["face_size"] == stratum] for k, v in d.items()}
        # mean +/- sd: the guideline asks for a standard deviation with every
        # measurement where one applies
        rows.append([label, len(g["infu"]),
                     ms(g["infu"]["id_loss_antelope"], "%.3f"),
                     ms(g["pulid4"]["id_loss_antelope"], "%.3f"),
                     ms(g["infu"]["id_loss_irse50"], "%.3f"),
                     ms(g["pulid4"]["id_loss_irse50"], "%.3f"),
                     ms(g["pulid0"]["id_loss_irse50"], "%.3f")])
    rows.append(None)
    rows.append(["published", "--", f"{PAPER['infu']['id']:.3f}", f"{PAPER['pulid']['id']:.3f}",
                 f"{PAPER['infu']['id']:.3f}", f"{PAPER['pulid']['id']:.3f}",
                 f"{PAPER['pulid']['id']:.3f}"])
    return tex_table(
        "Part 1 by face size",
        r"ID Loss by the face-size axis of the benchmark, mean $\pm$ standard "
        r"deviation over the cells with a detected face; $n$ is the number of "
        r"cells per stratum. Both methods "
        r"degrade along the same axis under both recognisers. The full-body stratum is 34\% of this "
        r"benchmark by design; the original work describes its own as a portrait "
        r"benchmark and does not publish its marginals. Under InfU's encoder the "
        r"close-up stratum comes close to the published level.",
        "tab:strata",
        ["Face size", "$n$", "InfU", "PuLID 4", "InfU", "PuLID 4", "PuLID 0"],
        rows, size="footnotesize\\setlength{\\tabcolsep}{4pt}",
        pre_header=r"& & \multicolumn{2}{c}{PuLID's encoder} & \multicolumn{3}{c}{InfU's encoder} \\"
                   "\n    \\cmidrule(lr){3-4}\\cmidrule(lr){5-7}")


def t_controls(S):
    """The authors'-portraits control and the text-only ceiling."""
    pid_f = S / "paperid_infu_manifest_paperid.parquet"
    ceil_f = S / "ceiling_prompts.parquet"
    if not pid_f.exists() and not ceil_f.exists():
        return None
    d = load_part1(S)
    rows = []
    if pid_f.exists():
        pid = pd.read_parquet(pid_f)
        irf = S / "irse50_paperid_infu_manifest_paperid.csv"
        if irf.exists():
            pid = pid.merge(pd.read_csv(irf)[["cell", "id_loss_irse50"]], on="cell", how="left")
        for c in ("id_loss_antelope", "id_loss_irse50"):
            pid[c] = pd.to_numeric(pid.get(c), errors="coerce")
        rows.append(["InfU, FRLL identities", len(d["infu"]),
                     f"{d['infu']['face_detected'].astype(float).mean():.3f}",
                     ms(d["infu"]["id_loss_antelope"]), ms(d["infu"]["id_loss_irse50"]), "--"])
        rows.append(["InfU, authors' portraits", len(pid),
                     f"{pid['face_detected'].astype(float).mean():.3f}",
                     ms(pid["id_loss_antelope"]), ms(pid["id_loss_irse50"]), "--"])
        rows.append(None)
    if ceil_f.exists():
        ceil = pd.read_parquet(ceil_f)
        n_prompts = len(ceil)
        # Weight each prompt by its Part 1 cell count so the ceiling mean and the
        # Part 1 means cover the same prompt distribution.
        if "weight" in ceil.columns:
            ceil = ceil.loc[ceil.index.repeat(ceil["weight"].astype(int))]
        rows.append(["Text-only FLUX (ceiling)", n_prompts, "--", "--", "--",
                     ms(ceil["clipscore_b32"])])
        rows.append(["InfU", len(d["infu"]), "--", "--", "--", ms(d["infu"]["clipscore_b32"])])
        rows.append(["PuLID 4", len(d["pulid4"]), "--", "--", "--", ms(d["pulid4"]["clipscore_b32"])])
        rows.append(["PuLID 0", len(d["pulid0"]), "--", "--", "--", ms(d["pulid0"]["clipscore_b32"])])
    return tex_table(
        "Two controls",
        r"Upper block: InfU on the only identities whose provenance is certain, "
        r"the example portraits published with the original work, every other "
        r"factor held fixed. Lower block: CLIPScore (ViT-B/32) of text-only "
        r"generation on this benchmark, the bound the original work's "
        r"text-alignment claim is stated against (it reports 0.334 on its "
        r"unreleased test set). The ceiling is one image per prompt, weighted by "
        r"the prompt's Part 1 cell count.",
        "tab:controls",
        ["Condition", "$n$", "Detection", "ID, PuLID's encoder", "ID, InfU's encoder", "CLIP B/32"],
        rows, size="footnotesize\\setlength{\\tabcolsep}{3pt}")


FILTERS = ["edge_preserve", "stylize_25", "stylize_45", "stylize_60"]


def floor_and_generated(S, key):
    """(floor frame with filter + loss, InfU Part 1 mean, PuLID-4 Part 1 mean) for one judge."""
    if key in ("glint", "w600k"):
        col = "id_loss_antelope" if key == "glint" else "id_loss_buffalo"
        f = pd.read_parquet(S / "id_floor.parquet").rename(columns={col: "loss"})
        gen = [pd.read_parquet(S / f"{m}_manifest_repro.parquet")[col] for m in ("infu_aes2", "pulid")]
    elif key in ("irse50", "fn_vgg"):
        col = "id_loss_irse50" if key == "irse50" else "id_loss_facenet"
        stem = "irse50" if key == "irse50" else "facenet"
        f = pd.read_csv(S / f"{stem}_floor.csv").rename(columns={col: "loss"})
        gen = [pd.read_csv(S / f"{stem}_{m}_manifest_repro.csv")[col] for m in ("infu_aes2", "pulid")]
    else:
        f = pd.read_csv(S / "panel" / f"{key}_floor.csv").rename(columns={f"id_loss_{key}": "loss"})
        f["filter"] = f["key"].str.split("__floor_").str[1].str.split("_", n=1).str[1]
        gen = [pd.read_csv(S / "panel" / f"{key}_{m}.csv")[f"id_loss_{key}"] for m in ("infu_aes2", "pulid")]
    return f, [pd.to_numeric(g, errors="coerce").mean() for g in gen]


def t_floor(S):
    """The floor under every judge, beside the generated images' own ID Loss.

    Judges are rows now that there are eight of them: the question the table
    answers is, per judge, whether rendering alone costs as much as generation.
    """
    rows = []
    for key, name in JUDGES:
        f, (gi, gp) = floor_and_generated(S, key)
        cells = [name]
        for flt in FILTERS:
            cells.append(ms(f.loc[f["filter"] == flt, "loss"], "%.3f"))
        cells.append(f"{gi:.3f} / {gp:.3f}")
        rows.append(cells)
        if key == "w600k":
            rows.append(None)
    return tex_table(
        "Domain-shift floor under every judge",
        r"ID Loss of each reference photograph filtered and scored against itself, "
        r"geometry unchanged (verified sub-pixel), mean $\pm$ standard deviation over "
        r"eight identities; the unfiltered photograph scores zero. Generated: mean ID "
        r"Loss of the Part 1 images of InfU / PuLID at start step 4 under the same "
        r"judge. The filters keep shading and structure, so the floor is a lower bound.",
        "tab:floor",
        ["Judge", "edge\\_preserve", "stylize\\_25", "stylize\\_45", "stylize\\_60", "Generated"],
        rows, align="lrrrrr", size="footnotesize\\setlength{\\tabcolsep}{4pt}")


def t_part2(S):
    """Styles across the columns rather than down the rows.

    The long form needed eighteen rows to say what six rows and three columns
    say, and it separated the two quantities that have to be read together:
    a method that declines to adopt a style preserves identity for free, so the
    ID Loss and style-adoption lines for one method belong next to each other.
    """
    STYLES = ["oil_painting", "render_3d", "watercolour"]
    PHRASES = ["photoreal"] + STYLES
    sp = pd.read_parquet(S / "style_phrases.parquet")

    def style_rows(method):
        """Style gain on one phrase, and how often CLIP names the requested style.

        Replaces the pre-registered style adoption, which compared a styled
        image against its style phrase with the photo against a different
        phrase (tools/score_style_phrases.py).
        """
        d = sp[sp["method"] == f"style_{method}"]
        photo = d[d["style"] == "photoreal"].set_index(["iid", "base_pid"])
        sys.path.insert(0, str(ROOT))
        from src.analysis.style_deltas import bootstrap_ci
        gains, ps, named, cis = [], [], [], []
        for st in STYLES:
            s = d[d["style"] == st].set_index(["iid", "base_pid"])
            x = (s[f"sim_l14_{st}"] - photo[f"sim_l14_{st}"].reindex(s.index)).dropna().to_numpy()
            gains.append(np.median(x))
            cis.append(bootstrap_ci(x))
            ps.append(stats.wilcoxon(x).pvalue)
            best = s[[f"sim_l14_{q}" for q in PHRASES]].to_numpy().argmax(1)
            named.append(np.mean(best == PHRASES.index(st)))
        m = len(ps)
        order, adj, run = np.argsort(ps), np.empty(m), 0.0
        for rank, i in enumerate(order):
            run = max(run, (m - rank) * ps[i])
            adj[i] = min(1.0, run)
        return ([f"${g:+.4f}${'$^{*}$' if p < 0.05 else ''}" for g, p in zip(gains, adj)],
                [ci_cell(c) for c in cis],
                [f"{v:.0%}".replace("%", "\\%") for v in named])

    def ci_cell(ci):
        return f"{{\\scriptsize$[{ci[0]:+.3f}, {ci[1]:+.3f}]$}}"

    # Every median carries its bootstrap 95% interval beside it, in a smaller
    # font: the guideline asks for a measure of dispersion with every
    # measurement, and one row per quantity keeps the table to a third of a page.
    rows = []
    for method in ["infu", "pulid"]:
        j = json.loads((S / f"part2_{method}.json").read_text())
        name = "InfU" if method == "infu" else "PuLID"
        gain, gain_ci, named = style_rows(method)
        first = True
        for metric, label in [("id_loss_antelope", "ID Loss"), ("gain", "Style gain"),
                              ("named", "Named as style"), ("fmi_photo", "FMI")]:
            who = name if first else ""
            first = False
            if metric == "gain":
                rows.append([who, label] + [f"{g}\\ {c}" for g, c in zip(gain, gain_ci)])
                continue
            if metric == "named":
                rows.append([who, label] + named)
                continue
            by_style = {r["style"]: r for r in j["metrics"].get(metric, [])}
            cells = []
            for st in STYLES:
                r = by_style.get(st)
                if r is None:
                    cells.append("--")
                    continue
                star = "$^{*}$" if r.get("significant") else ""
                cells.append(f"${r['median']:+.4f}${star}\\ {ci_cell(r['ci'])}")
            rows.append([who, label] + cells)
        rows.append(None)
    if rows and rows[-1] is None:
        rows.pop()
    return tex_table(
        "Part 2 paired style deltas",
        "Styled minus photorealistic control within a cell (same identity, base "
        "prompt and latent): medians with bootstrap 95\\% CI; $^{*}$ significant "
        "(Wilcoxon signed-rank, Holm across styles). Style gain: Equation~\\ref{eq:gain}, "
        "CLIP ViT-L/14. Named as style: share of styled images CLIP names as the "
        "requested style. FMI: Equation~\\ref{eq:fmi}. ID Loss: PuLID's encoder. $n$ "
        "per cell: 144 for the CLIP rows, 126 to 137 for ID Loss, 102 to 114 for FMI.",
        "tab:part2",
        ["Method", "Metric", "Oil painting", "3D render", "Watercolour"],
        rows, align="llrrr", size="footnotesize\\setlength{\\tabcolsep}{3pt}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scores", required=True)
    ap.add_argument("--out", default="report/tables")
    a = ap.parse_args()

    S = Path(a.scores)
    out = ROOT / a.out if not Path(a.out).is_absolute() else Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    builders = [("part1", t_part1_headline), ("strata", t_part1_strata),
                ("paired", t_paired), ("judges", t_judges), ("floor", t_floor),
                ("part2", t_part2), ("controls", t_controls)]
    made = []
    for name, fn in builders:
        try:
            tex = fn(S)
        except FileNotFoundError as e:
            print(f"  skip {name}: missing {Path(str(e).split()[-1]).name}")
            continue
        if tex is None:
            print(f"  skip {name}: inputs not scored yet")
            continue
        (out / f"{name}.tex").write_text(tex, encoding="ascii")
        made.append(name)
        print(f"  wrote {out / (name + '.tex')}")

    print(f"\n{len(made)} tables: {', '.join(made)}")
    print("Each uses booktabs rules only and carries a label, so the text can")
    print("reference it -- the guideline requires every table to be referenced.")
    return 0


